import { pixmap } from '../../journeys/pixmap';
import type { NeighbourSprites, PersonAnim, SpriteBox } from './cast-sprites';

function box(canvas: HTMLCanvasElement): SpriteBox {
  return { canvas, w: canvas.width, h: canvas.height };
}

function buildPerson(
  rowsIdle: readonly string[],
  rowsActive: readonly string[],
  palette: Readonly<Record<string, string>>,
): PersonAnim {
  return {
    idle: box(pixmap(rowsIdle, palette)),
    active: box(pixmap(rowsActive, palette)),
  };
}

