/** Screen pixels per icon pixel. Whole numbers keep the squares crisp. */
const ICON_SCALE = 2;

/** Turns rows of `#` and `.` into an SVG of square pixels in the current text colour. */
function pixels(rows: string[]): string {
  const w = rows[0].length;
  const runs: string[] = [];
  rows.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) runs.push(`M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`);
  });
  return `<svg viewBox="0 0 ${w} ${rows.length}" width="${w * ICON_SCALE}" height="${rows.length * ICON_SCALE}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true"><path d="${runs.join('')}"/></svg>`;
}

